create table if not exists public.offers (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  title text not null,
  description text not null default '',
  store text not null,
  category text not null,
  price numeric(12,2) not null check (price >= 0),
  old_price numeric(12,2) not null check (old_price > price),
  image_url text,
  start_date date,
  end_date date,
  created_at timestamptz not null default now()
);
alter table public.offers enable row level security;
drop policy if exists "Offers are publicly readable" on public.offers;
create policy "Offers are publicly readable" on public.offers for select using (true);
drop policy if exists "Authenticated users can create own offers" on public.offers;
create policy "Authenticated users can create own offers" on public.offers for insert to authenticated with check (auth.uid() = user_id);
drop policy if exists "Users can update own offers" on public.offers;
create policy "Users can update own offers" on public.offers for update to authenticated using (auth.uid() = user_id) with check (auth.uid() = user_id);
drop policy if exists "Users can delete own offers" on public.offers;
create policy "Users can delete own offers" on public.offers for delete to authenticated using (auth.uid() = user_id);

insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values ('offer-images', 'offer-images', true, 5242880, array['image/jpeg','image/png','image/webp','image/gif'])
on conflict (id) do update set public = true, file_size_limit = 5242880, allowed_mime_types = excluded.allowed_mime_types;
drop policy if exists "Offer images are publicly readable" on storage.objects;
create policy "Offer images are publicly readable" on storage.objects for select using (bucket_id = 'offer-images');
drop policy if exists "Users upload images to own folder" on storage.objects;
create policy "Users upload images to own folder" on storage.objects for insert to authenticated with check (bucket_id = 'offer-images' and (storage.foldername(name))[1] = auth.uid()::text);
drop policy if exists "Users update images in own folder" on storage.objects;
create policy "Users update images in own folder" on storage.objects for update to authenticated using (bucket_id = 'offer-images' and (storage.foldername(name))[1] = auth.uid()::text) with check (bucket_id = 'offer-images' and (storage.foldername(name))[1] = auth.uid()::text);
drop policy if exists "Users delete images in own folder" on storage.objects;
create policy "Users delete images in own folder" on storage.objects for delete to authenticated using (bucket_id = 'offer-images' and (storage.foldername(name))[1] = auth.uid()::text);
